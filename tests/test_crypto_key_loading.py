# Test 13: Duplicate key IDs and two current keys fail closed
def test_duplicate_and_double_current_fail_closed(key_dir):
    manifest = json.loads((key_dir / "manifest.json").read_text())
    first = manifest["keys"][0]

    write_manifest(key_dir, manifest["keys"] + [dict(first)])

    with pytest.raises(CryptoNotConfigured):
        build_service(key_dir=str(key_dir))

    second = dict(first, kid="audit.hmac-sha256.v2")
    write_manifest(key_dir, manifest["keys"] + [second])

    with pytest.raises(CryptoNotConfigured):
        build_service(key_dir=str(key_dir))


# Test 14: Error messages never contain key material
def test_errors_do_not_leak_key_material(tmp_path):
    secret = "c2VjcmV0LWtleS1tYXRlcmlhbA=="
    (tmp_path / "k").write_text(secret)
    write_manifest(tmp_path, [entry("audit.hmac-sha256.v1", "mac", "k")])

    with pytest.raises(CryptoNotConfigured) as error:
        build_service(key_dir=str(tmp_path))

    assert secret not in str(error.value)


