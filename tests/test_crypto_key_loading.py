# Test 7: Missing or malformed manifest fails closed
@pytest.mark.parametrize("content", [
    None, "{not json", "[]", '{"keys": {}}', '{"keys": [], "x": 1}',
])
def test_bad_manifest_fails_closed(tmp_path, content):
    if content is not None:
        (tmp_path / "manifest.json").write_text(content)

    with pytest.raises(CryptoNotConfigured):
        build_service(key_dir=str(tmp_path))


# Test 8: Invalid manifest entries fail closed
@pytest.mark.parametrize("change", [
    lambda e: e.update(purpose="ballot"),
    lambda e: e.update(alg="hmac-sha3-256"),
    lambda e: e.update(family="aead"),
    lambda e: e.update(kid="audit.hmac-sha256"),
    lambda e: e.update(file="../audit_hmac_v1"),
    lambda e: e.update(file="/etc/passwd"),
    lambda e: e.update(file="missing"),
    lambda e: e.update(current="yes"),
    lambda e: e.update(encoding="rot13"),
    lambda e: e.update(extra="x"),
    lambda e: e.pop("file"),
])
def test_invalid_manifest_entry_fails_closed(key_dir, change):
    manifest = json.loads((key_dir / "manifest.json").read_text())
    change(manifest["keys"][0])
    write_manifest(key_dir, manifest["keys"])

    with pytest.raises(CryptoNotConfigured):
        build_service(key_dir=str(key_dir))


