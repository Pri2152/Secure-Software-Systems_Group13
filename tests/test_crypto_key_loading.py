# Test 17: EVP_KEY_DIR configures module-level crypto
def test_env_key_dir_configures_crypto(clean_env, key_dir):
    clean_env.setenv("EVP_KEY_DIR", str(key_dir))

    envelope = crypto_agility.crypto.sign("results", DATA)

    assert envelope["kid"] == "results.ed25519.v1"
    assert crypto_agility.crypto.verify("results", DATA, envelope)


# Test 18: EVP_CRYPTO_POLICY switches the algorithm without code changes
def test_env_policy_file_switches_algorithm(clean_env, tmp_path):
    policy_path = tmp_path / "crypto_policy.json"
    policy_path.write_text(json.dumps(
        DEFAULT_POLICY.with_default(SIGN, "ecdsa-p256-sha256").to_dict()
    ))

    clean_env.setenv("EVP_CRYPTO_DEV_KEYS", "1")
    clean_env.setenv("EVP_CRYPTO_POLICY", str(policy_path))

    envelope = crypto_agility.crypto.sign("ballot", DATA)

    assert envelope["alg"] == "ecdsa-p256-sha256"


# Test 19: Policy file enabling the reserved PQC slot is refused
def test_policy_enabling_pqc_slot_is_refused(tmp_path):
    policy = DEFAULT_POLICY.to_dict()
    policy["defaults"]["sign"] = "ml-dsa-65"
    policy["allowed"]["sign"].append("ml-dsa-65")

    policy_path = tmp_path / "crypto_policy.json"
    policy_path.write_text(json.dumps(policy))

    with pytest.raises(crypto_agility.AlgorithmUnavailable):
        build_service(dev_keys=True, policy_path=str(policy_path))


# Test 20: Rotation without generation needs explicit key material
def test_directory_store_refuses_generated_rotation():
    store = KeyStore()

    with pytest.raises(crypto_agility.CryptoError):
        store.rotate("audit", HMAC_SHA256)

    entry_v1 = store.rotate(
        "audit", HMAC_SHA256, HMAC_SHA256.generate_key()
    )

    assert entry_v1.kid == "audit.hmac-sha256.v1"
    assert CryptoService(
        default_registry(), DEFAULT_POLICY, store
    ).mac("audit", DATA)["kid"] == "audit.hmac-sha256.v1"
