# Test 1: Keys load from a manifest and work for each family
def test_keys_load_from_directory(key_dir):
    service = build_service(key_dir=str(key_dir))

    mac = service.mac("audit", DATA)
    ciphertext = service.encrypt("pii", DATA)
    signature = service.sign("results", DATA)

    assert mac["kid"] == "audit.hmac-sha256.v1"
    assert service.verify_mac("audit", DATA, mac) is True
    assert service.decrypt("pii", ciphertext) == DATA
    assert service.verify("results", DATA, signature) is True


# Test 2: Keys survive a restart (same files, same results)
def test_loaded_keys_are_stable_across_restarts(key_dir):
    first = build_service(key_dir=str(key_dir))
    second = build_service(key_dir=str(key_dir))

    envelope = first.encrypt("pii", DATA)

    assert second.decrypt("pii", envelope) == DATA


# Test 3: Directory mode never generates missing keys
def test_directory_mode_does_not_generate_keys(key_dir):
    service = build_service(key_dir=str(key_dir))

    with pytest.raises(KeyNotFound):
        service.mac("ballot", DATA)


# Test 4: Public-only entry verifies but cannot sign
def test_public_only_entry_is_verify_only(tmp_path, key_dir, signing_key):
    signed = build_service(key_dir=str(key_dir)).sign("results", DATA)

    verifier_dir = tmp_path / "verifier"
    verifier_dir.mkdir()
    (verifier_dir / "results_sign_v1.pub").write_bytes(
        public_pem(signing_key)
    )
    write_manifest(verifier_dir, [
        entry("results.ed25519.v1", "sign", "results_sign_v1.pub"),
    ])

    verifier = build_service(key_dir=str(verifier_dir))

    assert verifier.verify("results", DATA, signed) is True

    with pytest.raises(KeyNotFound):
        verifier.sign("results", DATA)


# Test 5: Several versions: current one signs, old one verifies
def test_multiple_versions_from_directory(tmp_path):
    old_key = HMAC_SHA256.generate_key().secret
    new_key = HMAC_SHA256.generate_key().secret

    (tmp_path / "v1").write_text(base64.b64encode(old_key).decode())
    (tmp_path / "v2").write_text(base64.b64encode(new_key).decode())

    write_manifest(tmp_path, [
        entry("audit.hmac-sha256.v1", "mac", "v1"),
    ])
    old_envelope = build_service(key_dir=str(tmp_path)).mac("audit", DATA)

    write_manifest(tmp_path, [
        entry("audit.hmac-sha256.v1", "mac", "v1", current=False),
        entry("audit.hmac-sha256.v2", "mac", "v2"),
    ])
    rotated = build_service(key_dir=str(tmp_path))

    assert rotated.mac("audit", DATA)["kid"] == "audit.hmac-sha256.v2"
    assert rotated.verify_mac("audit", DATA, old_envelope) is True


# Test 6: Missing key directory fails closed
